"""End-to-end check of every feature against a RUNNING server (stdlib only).

    uvicorn app.main:app --port 8000          # in one terminal
    python scripts/verify_live.py             # in another (optional: base URL arg)

Prints PASS/FAIL per check and exits non-zero if anything failed.
"""
import json
import sys
import urllib.error
import urllib.request
import uuid
from concurrent.futures import ThreadPoolExecutor

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8000"
RUN = uuid.uuid4().hex[:8]  # keeps reference_ids unique across repeated runs
results = []


def call(method, path, body=None, raw=None):
    data = raw if raw is not None else (json.dumps(body).encode() if body is not None else None)
    req = urllib.request.Request(BASE + path, data=data, method=method)
    req.add_header("content-type", "application/json")
    try:
        with urllib.request.urlopen(req) as r:
            return r.status, json.loads(r.read() or b"null")
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read() or b"null")


def check(name, cond, info=""):
    results.append(cond)
    print(f"  {'PASS' if cond else 'FAIL'}  {name}" + ("" if cond else f"   -> {info}"))


def code(resp):
    return (resp[1] or {}).get("error", {}).get("code")


def new_account(name="Asha"):
    return call("POST", "/accounts", {"name": name})[1]["id"]


def tx(acc, type_, amount, ref, **extra):
    return call("POST", f"/accounts/{acc}/transactions",
                {"type": type_, "amount": amount, "reference_id": f"{RUN}-{ref}", **extra})


def bal(acc):
    return call("GET", f"/accounts/{acc}/balance")[1]["balance"]


def hist(acc, query=""):
    return call("GET", f"/accounts/{acc}/transactions{query}")


print(f"Verifying {BASE}\n")

print("0. Health")
check("GET /health -> 200", call("GET", "/health") == (200, {"status": "ok"}))

print("1. Create account")
s, a = call("POST", "/accounts", {"name": "Asha"})
check("201 Created", s == 201, s)
check("has id, name, balance, created_at", {"id", "name", "balance", "created_at"} <= set(a), a)
check("initial balance is 0", a["balance"] == 0, a)
check("created_at generated by system", bool(a["created_at"]), a)
ids = {new_account() for _ in range(10)}
check("ids are unique", len(ids) == 10)
r = call("POST", "/accounts", {"name": "Asha", "balance": 5000})
check("client cannot set balance -> 422", r[0] == 422, r)
check("client cannot set id -> 422", call("POST", "/accounts", {"name": "A", "id": "x"})[0] == 422)
check("client cannot set created_at -> 422",
      call("POST", "/accounts", {"name": "A", "created_at": "2020"})[0] == 422)
check("missing name -> 422", call("POST", "/accounts", {})[0] == 422)
check("blank name -> 422", call("POST", "/accounts", {"name": "   "})[0] == 422)
check("null name -> 422", call("POST", "/accounts", {"name": None})[0] == 422)
s, got = call("GET", f"/accounts/{a['id']}")
check("GET /accounts/{id} returns the account", s == 200 and got["id"] == a["id"], got)
check("GET unknown account -> 404 ACCOUNT_NOT_FOUND", code(call("GET", "/accounts/nope")) == "ACCOUNT_NOT_FOUND")

print("2. Transactions: credit / debit")
acc = a["id"]
s, t = tx(acc, "credit", 100, "c1", description="Opening deposit")
check("credit -> 201", s == 201, t)
check("transaction has all fields",
      {"id", "account_id", "type", "amount", "description", "reference_id", "created_at"} <= set(t), t)
check("credit 100: balance 0 -> 100", bal(acc) == 100)
tx(acc, "credit", 50, "c2")
check("credit 50: balance 100 -> 150", bal(acc) == 150)
s, _ = tx(acc, "debit", 30, "d1")
check("debit -> 201", s == 201)
check("debit 30: balance 150 -> 120", bal(acc) == 120)

print("2a. Insufficient balance")
r = tx(acc, "debit", 500, "d-big")
check("debit > balance -> 422 INSUFFICIENT_BALANCE", r[0] == 422 and code(r) == "INSUFFICIENT_BALANCE", r)
check("balance unchanged after rejection (120)", bal(acc) == 120)
check("rejected debit not stored", hist(acc)[1]["pagination"]["total_records"] == 3)
e = new_account()
tx(e, "credit", 40, "x")
check("debit exactly equal to balance allowed", tx(e, "debit", 40, "y")[0] == 201 and bal(e) == 0)

print("2b. Duplicate reference_id")
r = tx(acc, "credit", 999, "c1")
check("same ref same account -> 409 DUPLICATE_TRANSACTION", r[0] == 409 and code(r) == "DUPLICATE_TRANSACTION", r)
check("409 returns the original transaction",
      r[1]["error"]["details"]["existing_transaction"]["id"] == t["id"], r)
check("balance unchanged after duplicate (120)", bal(acc) == 120)
check("no new transaction created", hist(acc)[1]["pagination"]["total_records"] == 3)
r = tx(acc, "debit", 30, "d1")
check("retried debit reports duplicate, not insufficient", code(r) == "DUPLICATE_TRANSACTION", r)
b = new_account("Ravi")
check("same ref on a DIFFERENT account allowed", tx(b, "credit", 10, "c1")[0] == 201)

print("3. Balance")
s, body = call("GET", f"/accounts/{acc}/balance")
check("returns account_id + balance", s == 200 and body == {"account_id": acc, "balance": 120}, body)
r = call("GET", "/accounts/nope/balance")
check("unknown account -> 404 ACCOUNT_NOT_FOUND", r[0] == 404 and code(r) == "ACCOUNT_NOT_FOUND", r)

print("4. History: sort / filter / paginate")
h = new_account()
for i in range(7):
    tx(h, "credit", 10, f"hc{i}")
for i in range(3):
    tx(h, "debit", 1, f"hd{i}")
s, body = hist(h)
rows = body["data"]
check("no type -> both credit and debit", {x["type"] for x in rows} == {"credit", "debit"})
check("latest first (created_at descending)",
      [x["created_at"] for x in rows] == sorted((x["created_at"] for x in rows), reverse=True))
check("most recent transaction is first", rows[0]["reference_id"] == f"{RUN}-hd2", rows[0])
s, body = hist(h, "?type=credit")
check("type=credit -> only credits, total 7",
      {x["type"] for x in body["data"]} == {"credit"} and body["pagination"]["total_records"] == 7, body["pagination"])
s, body = hist(h, "?type=debit")
check("type=debit -> only debits, total 3",
      {x["type"] for x in body["data"]} == {"debit"} and body["pagination"]["total_records"] == 3, body["pagination"])
s, body = hist(h, "?limit=4&page=1")
p = body["pagination"]
check("pagination metadata: page, limit, total_records, total_pages",
      (p["page"], p["limit"], p["total_records"], p["total_pages"]) == (1, 4, 10, 3), p)
check("page 1 has 4 rows", len(body["data"]) == 4)
p3 = hist(h, "?limit=4&page=3")[1]
check("last page has remaining 2 rows", len(p3["data"]) == 2, p3)
all_ids = [x["id"] for pg in (1, 2, 3) for x in hist(h, f"?limit=4&page={pg}")[1]["data"]]
check("pages don't overlap or skip (10 unique ids)", len(set(all_ids)) == 10)
check("page past end -> empty list, not error", hist(h, "?page=99")[1]["data"] == [])
for q in ("?page=0", "?limit=0", "?limit=1000", "?page=abc"):
    r = hist(h, q)
    check(f"{q} -> 422 INVALID_PAGINATION", r[0] == 422 and code(r) == "INVALID_PAGINATION", r)
r = hist(h, "?type=refund")
check("type=refund -> 422 INVALID_TRANSACTION_TYPE", code(r) == "INVALID_TRANSACTION_TYPE", r)
check("history of unknown account -> 404", hist("nope")[0] == 404)

print("5. Data integrity")
c = new_account()
for i, (ty, amt) in enumerate([("credit", 100), ("credit", 50), ("debit", 30), ("debit", 20)]):
    tx(c, ty, amt, f"bc{i}")
check("brief example: +100 +50 -30 -20 = 100", bal(c) == 100)
for m in ("PUT", "PATCH", "DELETE"):
    check(f"{m} on transactions -> 405 (immutable)", call(m, f"/accounts/{acc}/transactions")[0] == 405)
check("DELETE a single transaction -> not possible",
      call("DELETE", f"/accounts/{acc}/transactions/{t['id']}")[0] in (404, 405))
check("transaction unchanged after attempts",
      any(x["id"] == t["id"] and x["amount"] == 100 for x in hist(acc)[1]["data"]))
f = new_account()
for i in range(10):
    tx(f, "credit", 0.1, f"f{i}")
check("money is exact: 10 x 0.1 = 1.0", bal(f) == 1.0, bal(f))

print("5a. Concurrency (parallel requests)")
k = new_account()
tx(k, "credit", 100, "seed")
with ThreadPoolExecutor(20) as pool:
    codes = list(pool.map(lambda i: tx(k, "debit", 30, f"par{i}")[0], range(20)))
check("20 parallel debits of 30 on 100 -> exactly 3 succeed", codes.count(201) == 3, codes)
check("balance never negative: ends at 10", bal(k) == 10, bal(k))
with ThreadPoolExecutor(20) as pool:
    codes = list(pool.map(lambda i: tx(k, "credit", 5, "same-ref")[0], range(20)))
check("20 parallel duplicates -> exactly 1 created", codes.count(201) == 1 and codes.count(409) == 19, codes)
check("balance moved once (10 -> 15)", bal(k) == 15, bal(k))

print("7/8. Validation and error format")
v = new_account()
cases = [
    ({"type": "refund", "amount": 10, "reference_id": "r"}, "INVALID_TRANSACTION_TYPE"),
    ({"amount": 10, "reference_id": "r"}, "INVALID_TRANSACTION_TYPE"),
    ({"type": "credit", "amount": 0, "reference_id": "r"}, "INVALID_AMOUNT"),
    ({"type": "credit", "amount": -5, "reference_id": "r"}, "INVALID_AMOUNT"),
    ({"type": "credit", "amount": "abc", "reference_id": "r"}, "INVALID_AMOUNT"),
    ({"type": "credit", "amount": 1.234, "reference_id": "r"}, "INVALID_AMOUNT"),
    ({"type": "credit", "reference_id": "r"}, "INVALID_AMOUNT"),
    ({"type": "credit", "amount": 10}, "VALIDATION_ERROR"),
    ({"type": "credit", "amount": 10, "reference_id": ""}, "VALIDATION_ERROR"),
]
for payload, want in cases:
    r = call("POST", f"/accounts/{v}/transactions", payload)
    check(f"{json.dumps(payload)} -> 422 {want}", r[0] == 422 and code(r) == want, r)
check("no invalid request changed the balance", bal(v) == 0)
r = call("POST", "/accounts/nope/transactions", {"type": "credit", "amount": 1, "reference_id": "r"})
check("transaction on unknown account -> 404", r[0] == 404 and code(r) == "ACCOUNT_NOT_FOUND", r)
r = call("POST", "/accounts", raw=b"{bad json")
check("malformed JSON -> 400 INVALID_REQUEST_BODY", r[0] == 400 and code(r) == "INVALID_REQUEST_BODY", r)
r = call("POST", "/accounts", [1, 2])
check("non-object body -> 400 INVALID_REQUEST_BODY", r[0] == 400 and code(r) == "INVALID_REQUEST_BODY", r)
r = call("GET", "/nowhere")
check("unknown route -> 404 NOT_FOUND", r[0] == 404 and code(r) == "NOT_FOUND", r)
check("every error has {error: {code, message, details}}",
      all(set(x[1]["error"]) == {"code", "message", "details"} for x in [r, call("GET", "/accounts/nope")]))

print("9. Bonus: transfer")
A, B = new_account("A"), new_account("B")
tx(A, "credit", 100, "sa")
tx(B, "credit", 50, "sb")
s, tr = call("POST", "/transfers", {"from_account_id": A, "to_account_id": B, "amount": 30,
                                    "reference_id": f"{RUN}-T1"})
check("transfer -> 201", s == 201, tr)
check("A: 100 -> 70, B: 50 -> 80", (bal(A), bal(B)) == (70, 80), (bal(A), bal(B)))
da = hist(A, "?type=debit")[1]["data"][0]
cb = hist(B, "?type=credit")[1]["data"][0]
check("debit leg in A's history, linked by transfer_id",
      da["id"] == tr["debit_transaction_id"] and da["transfer_id"] == tr["id"], da)
check("credit leg in B's history, linked by transfer_id",
      cb["id"] == tr["credit_transaction_id"] and cb["transfer_id"] == tr["id"], cb)
r = call("POST", "/transfers", {"from_account_id": A, "to_account_id": B, "amount": 30,
                                "reference_id": f"{RUN}-T1"})
check("retried transfer -> 409 DUPLICATE_TRANSFER", r[0] == 409 and code(r) == "DUPLICATE_TRANSFER", r)
check("no double transfer (still 70 / 80)", (bal(A), bal(B)) == (70, 80))
r = call("POST", "/transfers", {"from_account_id": A, "to_account_id": B, "amount": 9999,
                                "reference_id": f"{RUN}-T2"})
check("insufficient -> 422 INSUFFICIENT_BALANCE", code(r) == "INSUFFICIENT_BALANCE", r)
check("nothing partial: still 70 / 80", (bal(A), bal(B)) == (70, 80))
r = call("POST", "/transfers", {"from_account_id": A, "to_account_id": "ghost", "amount": 5,
                                "reference_id": f"{RUN}-T3"})
check("missing destination -> 404, A untouched", r[0] == 404 and bal(A) == 70, r)
r = call("POST", "/transfers", {"from_account_id": "ghost", "to_account_id": B, "amount": 5,
                                "reference_id": f"{RUN}-T4"})
check("missing source -> 404, B untouched", r[0] == 404 and bal(B) == 80, r)
r = call("POST", "/transfers", {"from_account_id": A, "to_account_id": A, "amount": 5,
                                "reference_id": f"{RUN}-T5"})
check("transfer to same account -> 422", r[0] == 422, r)
r = call("POST", "/transfers", {"from_account_id": A, "to_account_id": B, "amount": -5,
                                "reference_id": f"{RUN}-T6"})
check("negative transfer amount -> 422 INVALID_AMOUNT", code(r) == "INVALID_AMOUNT", r)

print("10. Docs")
check("Swagger UI at /docs -> 200", urllib.request.urlopen(BASE + "/docs").status == 200)
check("OpenAPI spec at /openapi.json -> 200", call("GET", "/openapi.json")[0] == 200)

passed = sum(results)
print(f"\n{passed}/{len(results)} checks passed" + ("" if passed == len(results) else "  <-- FAILURES ABOVE"))
sys.exit(0 if passed == len(results) else 1)
